// Наценка 16% — комиссия платёжного посредника (например: Claude $20 → $23.20 → RUB)
export const COMMISSION_PCT = 0.16;

function markup(usd: number, rate: number, pct = 1 + COMMISSION_PCT): number {
  return Math.ceil((usd * rate * pct) / 10) * 10;
}

// Цена за 1M токенов в рублях
function tok(usdPerM: number, rate: number): number {
  return Math.ceil(usdPerM * rate * 100) / 100;
}

