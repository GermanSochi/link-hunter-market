export async function POST(req: NextRequest) {
  // Только SUPERADMIN
  const session = await auth();
  if (!session?.user?.id) {
    return NextResponse.json({ error: "Unauthorized" }, { status: 401 });
  }

  // Проверяем роль пользователя
  const user = await prisma.user.findUnique({
    where: { id: session.user.id },
    select: { role: true },
  });

  if (!user || !["SUPERADMIN", "ADMIN"].includes(user.role)) {
    return NextResponse.json({ error: "Forbidden" }, { status: 403 });
  }

  const url = new URL(req.url);
  const overwrite = url.searchParams.get("overwrite") === "1";

  const results = [];

  for (const post of AI_BLOG_POSTS) {
    try {
      const existing = await prisma.post.findUnique({ where: { slug: post.slug } });

      if (existing && !overwrite) {
        results.push({ slug: post.slug, status: "skipped", reason: "already exists" });
        continue;
      }

      const data = {
        authorId: session.user.id,
        title: post.title,
        slug: post.slug,
        content: post.content,
        category: post.category,
        tags: post.tags,
        isGold: post.isGold,
        status: "PUBLISHED" as const,
      };

      if (existing && overwrite) {
        await prisma.post.update({ where: { slug: post.slug }, data });
        results.push({ slug: post.slug, status: "updated" });
      } else {
        await prisma.post.create({ data });
        results.push({ slug: post.slug, status: "created" });
      }
    } catch (err) {
      const message = err instanceof Error ? err.message : "Unknown error";
      results.push({ slug: post.slug, status: "error", error: message });
    }
  }

  const created = results.filter((r) => r.status === "created").length;
  const updated = results.filter((r) => r.status === "updated").length;
  const skipped = results.filter((r) => r.status === "skipped").length;
  const errors = results.filter((r) => r.status === "error").length;

  return NextResponse.json({
    success: errors === 0,
    summary: { total: AI_BLOG_POSTS.length, created, updated, skipped, errors },
    results,
    tip: "Add ?overwrite=1 to overwrite existing posts",
  });
}

// GET — список постов которые будут созданы
export async function GET() {
  const existing = await prisma.post.findMany({
    where: { slug: { in: AI_BLOG_POSTS.map((p) => p.slug) } },
    select: { slug: true },
  });
  const existingSlugs = new Set(existing.map((p) => p.slug));

  return NextResponse.json({
    posts: AI_BLOG_POSTS.map((p) => ({
      title: p.title,
      slug: p.slug,
      tags: p.tags,
      isGold: p.isGold,
      exists: existingSlugs.has(p.slug),
    })),
    usage: {
      seed: "POST /api/blog/seed-ai",
      overwrite: "POST /api/blog/seed-ai?overwrite=1",
    },
  });
}

// DELETE — удалить тестовые посты (чьи slug НЕ входят в AI_BLOG_POSTS)
export async function DELETE() {
  const session = await auth();
  if (!session?.user || (session.user as { role?: string }).role !== "admin") {
    return NextResponse.json({ error: "Forbidden" }, { status: 403 });
  }

  const knownSlugs = AI_BLOG_POSTS.map((p) => p.slug);

  const deleted = await prisma.post.deleteMany({
    where: { slug: { notIn: knownSlugs } },
  });

  return NextResponse.json({
    success: true,
    deleted: deleted.count,
    message: `Удалено ${deleted.count} тестовых постов`,
  });
}
